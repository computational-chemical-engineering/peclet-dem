"""Contract: the shipped type stub packaging/_dem.pyi covers every public name of peclet.dem._dem.

The stub is generated by nanobind.stubgen against an MPI-enabled host build (recipe in
CMakeLists.txt, next to the rule that stages it). A binding added without regenerating it fails
here. Names in the stub but absent at runtime fail too, except on a build without MPI, which lacks
the distributed-step names the stub carries.
"""
import ast
from pathlib import Path

from peclet.dem import _dem

STUB = Path(__file__).resolve().parents[2] / "packaging" / "_dem.pyi"
# Bound only under PECLET_DEM_MPI (src/dem_bindings.cpp).
MPI_ONLY = {"Simulation.init_mpi", "Simulation.enable_mpi_step", "Simulation.step_mpi",
            "Simulation.step_hertz_mpi", "Simulation.rebalance", "Simulation.migrate_to_weights",
            "Simulation.rank", "Simulation.num_ghost", "Diagnostics.mpi_rebuilds",
            "Diagnostics.mpi_gathers"}


def _public(name):
    return not name.startswith("_") or name == "__init__"


def _stub_names():
    tree = ast.parse(STUB.read_text())
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
        if isinstance(node, ast.ClassDef):
            for member in node.body:
                if isinstance(member, ast.FunctionDef) and _public(member.name):
                    names.add(f"{node.name}.{member.name}")
    return names


def _runtime_names():
    names = set()
    for name in dir(_dem):
        if name.startswith("_"):
            continue
        names.add(name)
        obj = getattr(_dem, name)
        if isinstance(obj, type):
            # A class without a bound constructor (Diagnostics) still has nanobind's refusing
            # __init__, which carries no signature and is not part of the API.
            names.update(f"{name}.{m}" for m, v in vars(obj).items()
                         if _public(m) and (m != "__init__" or hasattr(v, "__nb_signature__")))
    return names


def test_stub_covers_every_public_name():
    missing = sorted(_runtime_names() - _stub_names())
    assert not missing, (f"public names of peclet.dem._dem missing from {STUB.name}: {missing}; "
                         "regenerate the stub (recipe in CMakeLists.txt)")


def test_stub_names_exist_at_runtime():
    extra = _stub_names() - _runtime_names()
    if not hasattr(_dem.Simulation, "init_mpi"):  # a build without MPI: the stub lists more
        extra -= MPI_ONLY
    assert not extra, f"names in {STUB.name} that peclet.dem._dem does not define: {sorted(extra)}"
